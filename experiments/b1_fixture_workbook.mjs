import fs from 'node:fs/promises';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const [dataPath, requestedOutput] = process.argv.slice(2);
if (!dataPath || !requestedOutput) throw new Error('Expected input JSON and output directory');
const data = JSON.parse(await fs.readFile(dataPath, 'utf8'));
if (!data.synthetic || data.rows.length !== 12000) throw new Error('Expected 12000 synthetic rows');
const outputDir = path.resolve(requestedOutput, '..', 'outputs', 'b1_fixture');
await fs.mkdir(outputDir, { recursive: true });
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('SYNTHETIC_12000');
sheet.showGridLines = false;
sheet.getRange('A1:C12001').values = [data.headers, ...data.rows];
sheet.getRange('A1:C12001').format.font = { name: 'Arial', size: 10, color: '#1F2937' };
sheet.getRange('A1:C1').format = { fill: '#1F3A5F', font: { name: 'Arial', size: 10, bold: true, color: '#FFFFFF' } };
sheet.getRange('A1:C1').format.rowHeight = 28;
sheet.getRange('A2:C12001').format.rowHeight = 40;
sheet.getRange('A1:A12001').format.columnWidth = 16;
sheet.getRange('B1:B12001').format.columnWidth = 92;
sheet.getRange('C1:C12001').format.columnWidth = 40;
sheet.getRange('B2:C12001').format.wrapText = true;
sheet.getRange('A1:C12001').format.verticalAlignment = 'center';
sheet.freezePanes.freezeRows(1);
sheet.tables.add('A1:C12001', true, 'SyntheticCatalog');
workbook.recalculate();
const check = await workbook.inspect({ kind: 'table', range: 'SYNTHETIC_12000!A1:C4', include: 'values,formulas', tableMaxRows: 4, tableMaxCols: 3, maxChars: 2000 });
console.log(check.ndjson);
const errors = await workbook.inspect({ kind: 'match', searchTerm: '#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!|#SPILL!|#CALC!', options: { useRegex: true, maxResults: 10 }, maxChars: 1000 });
console.log(errors.ndjson);
const preview = await workbook.render({ sheetName: 'SYNTHETIC_12000', range: 'A1:C8', scale: 1.5, format: 'png' });
await fs.writeFile(path.join(outputDir, 'B1_catalog_preview.png'), new Uint8Array(await preview.arrayBuffer()));
const exported = await SpreadsheetFile.exportXlsx(workbook);
const xlsxPath = path.join(outputDir, 'B1_catalog_12000_SYNTHETIC.xlsx');
await exported.save(xlsxPath);
await fs.copyFile(xlsxPath, path.join(requestedOutput, 'B1_catalog_12000_SYNTHETIC.xlsx'));
console.log(JSON.stringify({ synthetic: true, rows: data.rows.length, xlsx: xlsxPath }));
